"""Writes tools/art/pxl/art/palette.px.js from tools/art/pixel/palette.py, so pxl art uses the same
"Bonfire Night" palette as every other picture in the game:

    python3 tools/art/pxl/gen_palette.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "../pixel"))
from palette import RAMPS  # noqa: E402

flat = {f"{n}{i}": c for n, cols in RAMPS.items() for i, c in enumerate(cols)}
src = f"""// GENERATED by tools/art/pxl/gen_palette.py from tools/art/pixel/palette.py. Do not edit.
// The "Bonfire Night" palette by name (BN.GOLD3). An art file picks its one-char keys with
// keys({{ g: "GOLD3", G: "GOLD1", k: "K0" }}): that sets the keys and one ramp per material used.
globalThis.BN = {json.dumps(flat, indent=0).replace(chr(10), " ")}
globalThis.keys = (map) => {{
  const out = {{}}
  for (const [k, v] of Object.entries(map)) {{
    if (!(v in BN)) throw new Error("not in the palette: " + v)
    out[k] = BN[v]
  }}
  pal(out)
  const byRamp = {{}}
  for (const [k, v] of Object.entries(map)) {{
    const m = v.match(/^([A-Z]+?)(\\d+)$/)
    ;(byRamp[m[1]] ??= []).push([+m[2], k])
  }}
  const rs = Object.values(byRamp).filter((r) => r.length > 1)
    .map((r) => r.sort((a, b) => a[0] - b[0]).map((e) => e[1]).join(""))
  if (rs.length) ramps(...rs)
}}
"""
os.makedirs(os.path.join(HERE, "art"), exist_ok=True)
open(os.path.join(HERE, "art/palette.px.js"), "w").write(src)
print(f"{len(flat)} colours")
