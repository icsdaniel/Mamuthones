F3 = _compile(F3_SRC)


def text_width(s, font, spacing=1, scale=1):
    w = 0
    for i, ch in enumerate(s):
        w += font[ch].shape[1] * scale
        if i < len(s) - 1:
            w += spacing * scale
    return w


def draw_text(canvas, s, x, y, ink, font, spacing=1, scale=1):
    """Stamp text into an ink-index canvas (numpy uint8 HxW)."""
    cx = x
    H, W = canvas.shape
    for ch in s:
        g = font[ch]
        if scale > 1:
            g = np.kron(g, np.ones((scale, scale), dtype=bool))
        h, w = g.shape
        ys, xs = np.nonzero(g)
        ys = ys + y
        xs = xs + cx
        ok = (ys >= 0) & (ys < H) & (xs >= 0) & (xs < W)
        canvas[ys[ok], xs[ok]] = ink
        cx += w + spacing * scale
    return cx


# ---------------------------------------------------------------- logo face
LW, LH, LT = 13, 17, 3  # glyph width, height, stroke


def logo_glyph(ch):
    g = np.zeros((LH, LW), dtype=bool)
    t = LT
    if ch == "O":
        g[:, :] = True
        g[t:LH - t, t:LW - t] = False
    elif ch == "N":
        g[:, :t] = True
        g[:, LW - t:] = True
        span = LH - 1
        for y in range(LH):
            x = t - 1 + round((LW - 2 * t) * y / span)
            g[y, max(0, x - 1):x + 2] = True
    elif ch == "A":
        g[:, :t] = True
        g[:, LW - t:] = True
        g[:t, :] = True
        mid = LH // 2
        g[mid - 1:mid + 2, :] = True
    elif ch == "Z":
        g[:t, :] = True
        g[LH - t:, :] = True
        span = LH - 2 * t - 1
        for i, y in enumerate(range(t, LH - t)):
            x = round((LW - t) * (1 - i / span))
            g[y, max(0, x - 1):min(LW, x + t)] = True
    elif ch == "S":
        mid = LH // 2
        g[:t, :] = True
        g[mid - 1:mid + 2, :] = True
        g[LH - t:, :] = True
        g[:mid, :t] = True
        g[mid:, LW - t:] = True
    # chamfer the outer corners: one pixel off each, a carved bevel
    for (yy, xx) in [(0, 0), (0, LW - 1), (LH - 1, 0), (LH - 1, LW - 1)]:
        g[yy, xx] = False
    return g
